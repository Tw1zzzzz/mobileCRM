        Данные Health Connect используются только для показа статистики внутри приложения. Они не передаются третьим лицам и не используются для рекламы. Доступ можно отозвать в настройках Health Connect.

        4. Faceit
        Если вы подключили Faceit, приложение запрашивает у Faceit Data API публичную статистику по нику, используя ваш API-ключ. Ключ хранится на устройстве в зашифрованном виде.

        5. Уведомления
        Напоминания о событиях, тестах и сне создаются на устройстве и не требуют передачи данных.

        6. Удаление данных
        Профиль → «Удалить аккаунт» удаляет аккаунт и все его данные с устройства безвозвратно. Удаление приложения также удаляет все данные.

        7. Бета-версия с сервером Pulse
        Если вы зарегистрировались в бета-версии и приняли условия бета-тестирования, данные аккаунта и ваши записи хранятся на сервере Pulse (хостинг Vercel, база данных Neon) за пределами России; пароль хранится на сервере только в виде криптографического хеша. Чтобы улучшать приложение, в бета-версии собирается аналитика использования: какие экраны открываются, сколько времени вы проводите в приложении, какие действия выполняете — без значений показателей здоровья. Аккаунт и все данные на сервере можно удалить в любой момент: Профиль → «Удалить аккаунт» или на странице /delete-account сайта Pulse.

        8. Контакты
        По вопросам обработки данных: support@pulse.app (укажите актуальный адрес перед публикацией).
    """.trimIndent()

