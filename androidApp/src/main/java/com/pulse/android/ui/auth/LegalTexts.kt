package com.pulse.android.ui.auth

/**
 * Draft legal texts for Android (the iOS versions with Health Connect and Android Keystore wording).
 * Review with a lawyer before publishing.
 */
enum class LegalDocument(val title: String) {
    PRIVACY("Политика конфиденциальности"), TERMS("Пользовательское соглашение");

    val text: String get() = if (this == PRIVACY) LegalTexts.privacy else LegalTexts.terms
}

object LegalTexts {
    private const val UPDATED = "15 октября 2026"

    val privacy = """
        Редакция от $UPDATED.

        1. Какие данные обрабатывает Pulse
        • Данные аккаунта: имя, email, роль, ссылка на профиль Faceit, код команды.
        • Записи, которые вы вносите: сон, питание и фото блюд, настроение и энергия, колесо баланса, результаты тестов, анкета игрока (цели, роль, уровень) и самооценка «Игровой характер», тренировки, экранное время, события календаря, дневник CS2, цели.
        • Данные Health Connect — только после вашего разрешения и только для чтения: шаги, дистанция, активная энергия, пульс, пульс покоя, вариабельность пульса, дыхание, кислород в крови, сон, тренировки, вес и состав тела.
        • Статистика использования приложений — только после вашего разрешения, для подсчёта экранного времени.
        • Игровые данные Faceit — только если вы подключили Faceit своим API-ключом.

        2. Где хранятся данные
        Все данные хранятся только на вашем устройстве, в закрытой папке приложения. Пароль не сохраняется: хранится только его криптографический хеш, зашифрованный ключом из Android Keystore. Резервное копирование в облако для данных Pulse отключено. Мы не передаём ваши данные на свои серверы, не используем рекламу и трекинг, не продаём и не передаём данные третьим лицам.

        3. Health Connect
        Данные Health Connect используются только для показа статистики внутри приложения. Они не передаются третьим лицам и не используются для рекламы. Доступ можно отозвать в настройках Health Connect.

        4. Faceit
        Если вы подключили Faceit, приложение запрашивает у Faceit Data API публичную статистику по нику, используя ваш API-ключ. Ключ хранится на устройстве в зашифрованном виде.

        5. Уведомления
        Напоминания о событиях, тестах и сне создаются на устройстве и не требуют передачи данных.

        6. Удаление данных
        Профиль → «Удалить аккаунт» удаляет аккаунт и все его данные с устройства безвозвратно. Удаление приложения также удаляет все данные.

        7. Будущая синхронизация
        Когда появится сервер Pulse для синхронизации с веб-версией и командой, мы обновим эту политику и попросим отдельного согласия до передачи данных.

        8. Контакты
        По вопросам обработки данных: support@pulse.app (укажите актуальный адрес перед публикацией).
    """.trimIndent()

    val terms = """
        Редакция от $UPDATED.

        1. Pulse — приложение для самонаблюдения игроков в киберспорт: сон, питание, физическая активность, самочувствие, когнитивные тесты и игровая статистика.

        2. Pulse не является медицинским изделием и не ставит диагнозов. Оценки сна, восстановления, нагрузки и «формы дня» — ориентиры для самоконтроля, а не медицинские рекомендации. При проблемах со здоровьем обратитесь к врачу.

        3. Вы отвечаете за достоверность внесённых данных и за сохранность доступа к устройству. Данные хранятся на устройстве; при его утере или удалении приложения они могут быть утрачены.

        4. Игровые данные предоставляются Faceit. Pulse не связан с Faceit и не отвечает за доступность и точность их данных.

        5. Демо-режим содержит вымышленные данные для ознакомления.

        6. Мы можем обновлять приложение и эти условия; актуальная редакция всегда доступна в приложении.
    """.trimIndent()
}
