        • Статистика использования приложений — только после вашего разрешения, для подсчёта экранного времени.
        • Игровые данные Faceit — только если вы подключили Faceit своим API-ключом.

        2. Где хранятся данные
        Все данные хранятся только на вашем устройстве, в закрытой папке приложения (в бета-версии — см. раздел 7). Пароль не сохраняется: хранится только его криптографический хеш, зашифрованный ключом из Android Keystore. Резервное копирование в облако для данных Pulse отключено. Мы не передаём ваши данные на свои серверы (кроме бета-версии, раздел 7), не используем рекламу и трекинг, не продаём и не передаём данные третьим лицам.

